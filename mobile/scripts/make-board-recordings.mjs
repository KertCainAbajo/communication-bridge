// Makes the ready-made recordings of every board phrase and quick word with the bundled MMS voices,
// so tapping them plays at once on every phone (no speech to make). Writes assets/speech/*.m4a and
// offlineSpeech.ts. Run again whenever phrases or quick words change.
//
// Usage (from mobile/): node scripts/make-board-recordings.mjs <python with sherpa-onnx>
//   e.g. node scripts/make-board-recordings.mjs D:/voice-test/venv/Scripts/python.exe
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const python = process.argv[2];
if (!python) throw new Error('Give the path of a Python that has sherpa-onnx, numpy and imageio-ffmpeg.');

// Uses the app's own text helpers, so the keys and spoken text match what the app does.
const source = readFileSync(join(root, 'speechText.ts'), 'utf8');
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } });
const speechText = {};
new Function('exports', outputText)(speechText);
const { normalizeSpeechKey, prepareForMms, respellForEnglishVoice } = speechText;

// Quick words, as in App.tsx (key, English, Filipino).
const app = readFileSync(join(root, 'App.tsx'), 'utf8');
const quickWords = [...app.matchAll(/\{ key: '[^']+', en: '([^']+)', fil: '([^']+)'/g)].map((match) => ({ en: match[1], fil: match[2] }));
if (quickWords.length === 0) throw new Error('Quick words not found in App.tsx');

const content = JSON.parse(readFileSync(join(root, 'assets', 'offline', 'content.json'), 'utf8'));
const texts = { en: new Set(), fil: new Set() };
for (const language of ['en', 'fil']) {
  for (const message of content.languages[language].messages) {
    if (message.message_text) texts[language].add(message.message_text.trim());
  }
  for (const word of quickWords) texts[language].add(word[language]);
}

const entries = [];
const seen = new Set();
for (const language of ['en', 'fil']) {
  for (const text of texts[language]) {
    const key = `${language}:${normalizeSpeechKey(text)}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const file = `${language}-${createHash('sha1').update(key).digest('hex').slice(0, 12)}.m4a`;
    entries.push({ key, voice: language, text, prepared: language === 'en' ? prepareForMms(text, 'en') : respellForEnglishVoice(text, language), file });
  }
}

const outDir = join(root, 'assets', 'speech');
mkdirSync(outDir, { recursive: true });
// Recordings no longer used are removed.
const wanted = new Set(entries.map((entry) => entry.file));
for (const file of readdirSync(outDir)) {
  if (file.endsWith('.m4a') && !wanted.has(file)) rmSync(join(outDir, file));
}

const manifest = join(tmpdir(), `board-recordings-${process.pid}.json`);
writeFileSync(manifest, JSON.stringify(entries));
execFileSync(python, ['-I', join(root, 'scripts', 'render-board-recordings.py'), manifest, outDir, join(root, 'native-assets', 'models')], { stdio: 'inherit' });
rmSync(manifest);

const missing = entries.filter((entry) => !existsSync(join(outDir, entry.file)));
if (missing.length) throw new Error(`Recordings missing: ${missing.map((entry) => entry.key).join(', ')}`);

const lines = entries.map((entry) => `  ${JSON.stringify(entry.key)}: require('./assets/speech/${entry.file}'),`);
writeFileSync(join(root, 'offlineSpeech.ts'), `// Generated by scripts/make-board-recordings.mjs. Do not edit by hand.
// Maps "<language>:<text>" to a ready-made recording (the built-in voice), so board phrases and quick
// words play at once on every phone, with no internet.
export const offlineSpeech: Record<string, number> = {
${lines.join('\n')}
};
`);
console.log(`offlineSpeech.ts written with ${entries.length} recordings`);
