<?php

namespace App\Console\Commands;

use App\Services\SpeechSynthesisService;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;
use Throwable;

#[Signature('app:export-offline-speech
    {--mobile= : Path to the Expo app (defaults to ../mobile)}
    {--force : Regenerate audio files that already exist}')]
#[Description('Pre-generate Filipino audio for every preset message and bundle it into the mobile app')]
class ExportOfflineSpeech extends Command
{
    /**
     * Execute the console command.
     */
    public function handle(SpeechSynthesisService $speech): int
    {
        $mobilePath = rtrim((string) ($this->option('mobile') ?: base_path('../mobile')), '/\\');
        $contentFile = "{$mobilePath}/assets/offline/content.json";
        $audioDirectory = "{$mobilePath}/assets/offline/speech";
        $manifestFile = "{$mobilePath}/offlineSpeech.ts";

        if (! File::exists($contentFile)) {
            $this->error("Missing {$contentFile}. Run `node scripts/export-offline-content.mjs` in the mobile app first.");

            return self::FAILURE;
        }

        if (! $speech->isConfigured()) {
            $this->error('GIGGY_API_KEY is not set in backend/.env.');

            return self::FAILURE;
        }

        /** @var array{languages: array<string, array{messages: list<array{message_text: ?string}>}>} $content */
        $content = json_decode(File::get($contentFile), true, flags: JSON_THROW_ON_ERROR);
        File::ensureDirectoryExists($audioDirectory);

        /** @var array<string, string> $manifest */
        $manifest = [];
        $failedCount = 0;

        foreach ($speech->supportedLanguages() as $languageCode) {
            $texts = collect($content['languages'][$languageCode]['messages'] ?? [])
                ->pluck('message_text')
                ->filter(fn (mixed $text): bool => is_string($text) && trim($text) !== '')
                ->map(fn (string $text): string => trim($text))
                ->unique()
                ->values();

            $this->info("{$languageCode}: {$texts->count()} phrases");

            foreach ($texts as $text) {
                $fileName = $languageCode.'-'.substr(sha1("{$languageCode}|{$text}"), 0, 16).'.mp3';
                $filePath = "{$audioDirectory}/{$fileName}";

                if ($this->option('force') || ! File::exists($filePath)) {
                    try {
                        File::put($filePath, $speech->synthesize($text, $languageCode));
                        $this->line("  generated: {$text}");
                    } catch (Throwable $exception) {
                        $failedCount++;
                        $this->warn("  failed: {$text} ({$exception->getMessage()})");

                        continue;
                    }
                }

                $manifest["{$languageCode}:{$text}"] = $fileName;
            }
        }

        $this->writeManifest($manifestFile, $manifest);
        $this->info('Bundled '.count($manifest)." audio files into {$manifestFile}.");

        if ($failedCount > 0) {
            $this->warn("{$failedCount} phrases failed. Run the command again to retry them.");

            return self::FAILURE;
        }

        return self::SUCCESS;
    }

    /**
     * @param  array<string, string>  $manifest
     */
    private function writeManifest(string $manifestFile, array $manifest): void
    {
        $lines = collect($manifest)
            ->map(fn (string $fileName, string $key): string => '  '.json_encode($key, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES)
                .": require('./assets/offline/speech/{$fileName}'),")
            ->implode("\n");

        File::put($manifestFile, <<<TS
        // Generated by `php artisan app:export-offline-speech`. Do not edit by hand.
        // Maps "<language>:<text>" to bundled audio so preset phrases speak with no internet.
        export const offlineSpeech: Record<string, number> = {
        {$lines}
        };

        TS);
    }
}
